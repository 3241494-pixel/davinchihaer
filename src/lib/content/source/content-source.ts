/**
 * Контракт источника данных для каталога. products.ts работает только через
 * этот интерфейс — подмена файлового источника на CMS не требует правки
 * вызывающего кода, только новой реализации ContentSource.
 */
export interface ContentSource {
  /** Сырые, ещё не провалидированные записи товаров. */
  getProductsRaw(): unknown[];
  /** Сырые, ещё не провалидированные записи оттенков. */
  getColorsRaw(): unknown[];
}
